"""
Domain models and strongly-typed schemas for Partition-Aware Text2GQL.
Built with Pydantic v2 for maximum validation safety and serialization fidelity.
"""

from enum import Enum
from typing import List, Dict, Set, Optional, Any, Union
from pydantic import BaseModel, Field, ConfigDict


class QueryIntent(str, Enum):
    """Classified intent of the natural language graph query."""
    LOOKUP = "lookup"
    PATH_TRAVERSAL = "path_traversal"
    AGGREGATION = "aggregation"
    MULTI_HOP_JOIN = "multi_hop_join"
    SUBGRAPH_EXTRACTION = "subgraph_extraction"


class SchemaElementType(str, Enum):
    """Categorization of graph schema primitives."""
    NODE_LABEL = "node_label"
    RELATIONSHIP_TYPE = "relationship_type"
    PROPERTY = "property"


class EntitySpan(BaseModel):
    """Extracted entity/attribute/value span from natural language."""
    model_config = ConfigDict(frozen=True)

    text: str = Field(description="Literal text extracted from user question")
    start_char: int = Field(description="Start character offset in NL prompt")
    end_char: int = Field(description="End character offset in NL prompt")
    tag: str = Field(description="BIO tag or semantic category, e.g. ENTITY, ATTRIBUTE, VALUE")
    normalized_value: Optional[Any] = Field(default=None, description="Type-cast or canonical form")
    confidence: float = Field(default=1.0, description="Extraction confidence score in [0.0, 1.0]")


class SchemaElement(BaseModel):
    """Metadata for a graph schema primitive augmented with physical partition ownership."""
    name: str = Field(description="Element identifier (e.g. 'Movie', 'directedBy', 'release_year')")
    element_type: SchemaElementType
    owning_partitions: List[int] = Field(default_factory=list, description="Physical partitions where instances reside")
    domain: str = Field(default="default", description="Domain graph name")
    description: str = Field(default="", description="Semantic description for embedding retrieval")
    associated_label: Optional[str] = Field(default=None, description="Parent node/rel label if this is a property")


class PartitionTopology(BaseModel):
    """Physical partition configuration and cut boundaries for a distributed graph."""
    domain: str
    num_partitions: int = 4
    partition_sizes: Dict[int, int] = Field(default_factory=dict)
    edge_cut_ratio: float = 0.0
    boundary_edges: Dict[str, int] = Field(default_factory=dict, description="Count of edges between (part_i, part_j)")
    primary_labels_per_partition: Dict[int, List[str]] = Field(default_factory=dict)


class PlanType(str, Enum):
    """Execution strategy path."""
    PATH_A_NAIVE = "Path_A_Naive_ScatterGather"
    PATH_B_OPTIMIZED = "Path_B_PartitionAware_Rewritten"


class ShardSubquery(BaseModel):
    """Localized openCypher subquery dispatched to a specific physical shard."""
    subquery_id: str
    partition_id: int
    cypher_text: str
    input_bindings: Dict[str, Any] = Field(default_factory=dict)
    projected_join_keys: List[str] = Field(default_factory=list)
    projected_payload_keys: List[str] = Field(default_factory=list)
    depends_on: List[str] = Field(default_factory=list, description="IDs of prerequisite subqueries")


class BoundaryJoinSpec(BaseModel):
    """Specification for distributed result aggregation across shard boundaries."""
    left_subquery_id: str
    right_subquery_id: str
    join_keys: List[str]
    join_type: str = "INNER"  # INNER, LEFT, CROSS


class PhysicalExecutionPlan(BaseModel):
    """Complete physical execution plan generated by the cost-based optimizer."""
    plan_id: str
    plan_type: PlanType
    subqueries: List[ShardSubquery] = Field(default_factory=list)
    boundary_joins: List[BoundaryJoinSpec] = Field(default_factory=list)
    global_return_clause: str
    estimated_cost: float = 0.0
    estimated_shuffle_bytes: int = 0
    estimated_cross_hops: int = 0


class ExecutionMetrics(BaseModel):
    """High-resolution instrumentation for end-to-end and per-shard execution."""
    plan_type: PlanType
    latency_ms: float = Field(description="Total end-to-end execution time in ms")
    cross_partition_hops: int = Field(description="Number of physical network boundary crossings")
    network_shuffle_volume_bytes: int = Field(description="Bytes transferred between shards and coordinator")
    subqueries_dispatched: int = Field(description="Number of shard queries executed")
    shard_latencies_ms: Dict[int, float] = Field(default_factory=dict)
    intermediate_rows_shuffled: int = Field(default=0)
    final_result_count: int = Field(default=0)


class CostComparisonReport(BaseModel):
    """Side-by-side audit comparing Path A (Naive) vs Path B (Optimized)."""
    domain: str
    nl_question: str
    gold_cypher: Optional[str] = None
    path_a_metrics: ExecutionMetrics
    path_b_metrics: ExecutionMetrics
    latency_speedup_factor: float
    hop_reduction_pct: float
    shuffle_volume_reduction_pct: float
    semantic_equivalence: bool = Field(description="True if Path A and Path B produced identical result sets")

